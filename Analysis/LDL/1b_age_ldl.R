library(data.table)
library(lme4)

dat=fread("../../Data/dat_adult.tab")

ldldat=dat[which(!is.na(dat$ldl_max)),]
ldldat$variant=factor(ldldat$variant, levels=c("Not high risk","PRS+","FH+"))
ldldat$age_cat=factor(ldldat$age_cat)

ldldat[, age_centered := age_deid - mean(age_deid), by = age_cat]

# fit model
fit_strat <- lm(
  ldl_most_recent ~ variant * age_cat + age_centered + sex_at_birth_deid + site,
  data = ldldat
)

coefstrat <- summary(fit_strat)$coef
vcovstrat <- vcov(fit_strat)

# get coefficient names
coefnames <- rownames(coefstrat)

# initialize results
resage <- data.table(
  Comparison = rep(c("PRS+ vs. NHR", "FH+ vs. NHR"), each = length(levels(ldldat$age_cat))),
  Age = rep(levels(ldldat$age_cat), 2)
)

# function to calculate contrast and SE
get_effect <- function(base, interaction, comp, age_level) {
  
  beta <- coefstrat[base, "Estimate"]
  
  if (!is.na(interaction) && interaction %in% coefnames) {
    beta <- beta + coefstrat[interaction, "Estimate"]
    
    se <- sqrt(
      vcovstrat[base, base] +
      vcovstrat[interaction, interaction] +
      2 * vcovstrat[base, interaction]
    )
  } else {
    se <- coefstrat[base, "Std. Error"]
  }
  
  data.table(
    Beta = beta,
    SE = se
  )
}

# identify reference age category
age_levels <- levels(ldldat$age_cat)

# assuming first age category is reference and variant is coded with:
# variantPRS+ and variantFH+ compared to NHR
prs_base <- "variantPRS+"
fh_base  <- "variantFH+"

out <- list()

for (i in seq_along(age_levels)) {
  
  age <- age_levels[i]
  
  # interaction term names generated by R
  prs_int <- if (i == 1) NA else paste0("variantPRS+:age_cat", age)
  fh_int  <- if (i == 1) NA else paste0("variantFH+:age_cat", age)
  
  out[[length(out)+1]] <- cbind(
    data.table(Comparison="PRS+ vs. NHR", Age=age),
    get_effect(prs_base, prs_int)
  )
  
  out[[length(out)+1]] <- cbind(
    data.table(Comparison="FH+ vs. NHR", Age=age),
    get_effect(fh_base, fh_int)
  )
}

resage <- rbindlist(out)

resage[, `:=`(
  LB = Beta - 1.96*SE,
  UB = Beta + 1.96*SE,
  P = 2*pt(-abs(Beta/SE), df=df.residual(fit_strat))
)]

write.table(resage, "../../Results/ldl_age.tab", quote=FALSE, row.names=FALSE, sep="\t")

